// Package models defines essential struct or interface
package models

import (
	"log"
	"time"
)

type Field string

// Field on sql
const (
	// FieldNone is a mark for none field
	FieldNone Field = ""
	// only such fields can be update by [Database.Update]
	FieldTitle   Field = "title"
	FieldSummary Field = "summary"
	FieldSource  Field = "source"

	// For these fields, they should not updated by [Database.Update] function, drop them before Update
	FieldID         Field = "id"
	FieldOccurTime  Field = "occur_time"
	FieldCreateTime Field = "create_time"
	FieldFormat     Field = "format"
	FieldIsDelete   Field = "is_delete"
)

// isMutable is a map check if specific [Field] is mutable
// if mutable, return true
// else, false
var isMutable = map[Field]bool{
	FieldTitle:   true,
	FieldSummary: true,
	FieldSource:  true,

	FieldID:         false,
	FieldOccurTime:  false,
	FieldCreateTime: false,
	FieldFormat:     false,
	FieldIsDelete:   false,
}

// IsMutableField return if this [Field] is mutable
func IsMutableField(f Field) bool {
	mutable, ok := isMutable[f]
	if !ok {
		log.Fatalf("Field not in isMutable map, fix your code !!! field: %s", f)
	}

	return mutable
}

// DropUnmutableFields drop fields that should not updated by [Database.Update]
func DropUnmutableFields(attr map[Field]any) {
	for f := range attr {
		if !IsMutableField(f) {
			delete(attr, f)
		}
	}
}

// Event struct define for
type Event struct {
	// ID is the distinct identity for this event
	ID int

	// Title contains a few words describe this event
	// This field is mutable
	Title string

	// Summary
	// This field is mutable
	Summary string

	// OccurTime record when this event happened
	OccurTime time.Time

	// CreateTime is auto generated by database
	// It record when this event is inserted into database
	CreateTime time.Time

	// The format of source
	Format FormatType

	// Source contains comprehensive content about this event
	// It should be objective. You can add some links for repository or pictures
	//
	// This field is mutable
	Source string

	// IsDel mark if this event have been soft-deleted
	// 1 deleted
	// 0 not deleted
	IsDel int
}

// Equal return if e and o is value equal
//
// if not equal, return the first not match field
// compare All Fields
func (e *Event) Equal(o *Event) (bool, Field) {
	if e.ID != o.ID {
		return false, FieldID
	}

	if e.Title != o.Title {
		return false, FieldTitle
	}

	if e.Summary != o.Summary {
		return false, FieldSummary
	}

	if !e.CreateTime.Equal(o.CreateTime) {
		return false, FieldCreateTime
	}

	if !e.OccurTime.Equal(o.OccurTime) {
		return false, FieldOccurTime
	}

	if e.Format != o.Format {
		return false, FieldFormat
	}

	if e.Source != o.Source {
		return false, FieldSource
	}

	if e.IsDel != o.IsDel {
		return false, FieldIsDelete
	}

	return true, FieldNone
}
